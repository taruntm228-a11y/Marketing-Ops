import * as cheerio from "cheerio";
// cheerio 1.x re-exports its node types from domhandler rather than its own namespace.
import type { AnyNode, Element } from "domhandler";
import type { Company } from "./types";
import { absolutise, looksLikeCompany } from "./html";

/**
 * Parse an exhibitor directory WITHOUT an AI model.
 *
 * Directory pages are machine-generated, so the same markup repeats once per
 * exhibitor. We don't need to know whether this is a2z, MapYourShow or ExpoFP —
 * we just need to find the biggest repeating group and read it.
 *
 * Two strategies, we keep whichever finds more rows:
 *   A. a long table  → one company per row
 *   B. repeated link containers → one company per link
 */
export function extractStructural(html: string, sourceUrl: string): Company[] {
  const $ = cheerio.load(html);
  $("script, style, noscript, svg, head, nav, footer").remove();

  const fromTable = tableStrategy($, sourceUrl);
  const fromLinks = linkClusterStrategy($, sourceUrl);

  return fromTable.length >= fromLinks.length ? fromTable : fromLinks;
}

function tableStrategy($: cheerio.CheerioAPI, sourceUrl: string): Company[] {
  let best: Company[] = [];
  const scrapedAt = new Date().toISOString();

  $("table").each((_, table) => {
    const rows = $(table).find("tr");
    if (rows.length < 4) return;

    // Read the header so we can find the booth column rather than guess at it.
    const headers = $(rows[0])
      .find("th, td")
      .map((_, c) => $(c).text().trim().toLowerCase())
      .get();
    const boothCol = headers.findIndex((h) => /booth|stand|space/.test(h));
    const catCol = headers.findIndex((h) => /categor|sector|product|type/.test(h));
    const hasHeader = headers.some((h) => /company|exhibitor|name|booth|stand/.test(h));

    const out: Company[] = [];
    rows.slice(hasHeader ? 1 : 0).each((_, row) => {
      const cells = $(row).find("td");
      if (cells.length === 0) return;

      const link = $(row).find("a").first();
      const name = (link.text().trim() || $(cells[0]).text().trim()).replace(/\s+/g, " ");
      if (!looksLikeCompany(name)) return;

      out.push({
        name,
        website: absolutise(link.attr("href"), sourceUrl),
        booth: boothCol >= 0 ? $(cells[boothCol]).text().trim() || null : null,
        category: catCol >= 0 ? $(cells[catCol]).text().trim() || null : null,
        role: "unknown",
        sourceUrl,
        scrapedAt,
        evidence: spacedText($, $(row)).slice(0, 300),
      });
    });

    if (out.length > best.length) best = out;
  });

  return best;
}

/**
 * cheerio's .text() concatenates sibling elements with no separator, so
 * `<a>Riverbend Controls</a><span>Booth 418</span>` comes back as
 * "Riverbend ControlsBooth 418" and a \bbooth\b regex can never match.
 * Clone the subtree, put a space after every element, then read it.
 */
function spacedText($: cheerio.CheerioAPI, $node: cheerio.Cheerio<AnyNode>): string {
  if ($node.length === 0) return "";
  const $clone = $node.clone();
  // Braces matter: .each() expects void or boolean, and .after() returns a Cheerio.
  $clone.find("*").each((_, child) => {
    $(child).after(" ");
  });
  return $clone.text().replace(/\s+/g, " ").trim();
}

/**
 * Group links by the folder they point into, plus how deep they sit in the page.
 *
 * Directories come in two shapes and this has to handle both:
 *   - one shared handler with the id in the query
 *     (…/Public/openURL.aspx?BoothID=126905) — identical paths
 *   - a page per exhibitor (/exhibitors/riverbend) — every path different
 * Taking the folder rather than the full path collapses the second shape into
 * one group. Folder alone would also sweep in a site's nav, which often lives
 * in the same folder, so DOM depth is added: listings are generated by one loop
 * and sit at a uniform depth, while nav links sit at another.
 */
function linkFolder(href: string, base: string): string {
  let path: string;
  try {
    path = new URL(href, base).pathname;
  } catch {
    path = href.split("?")[0];
  }
  return path.slice(0, path.lastIndexOf("/") + 1).toLowerCase();
}

function depth($el: cheerio.Cheerio<Element>): number {
  return $el.parents().length;
}

/**
 * Pull a booth number out of the text around a listing.
 *
 * Two shapes, in order of confidence:
 *   1. labelled — "Booth 1406", "Stand #B22"
 *   2. bare — a table whose column header said BOOTH#, so the cell is just
 *      "1406" sitting next to the company name with no label at all. Common,
 *      and missed entirely by an earlier version that required the word.
 * For the bare case the company name is removed first, so digits inside the
 * name ("3M", "Group 4 Security") can't be mistaken for a booth.
 */
function findBooth(context: string, name: string): string | null {
  const labelled = context.match(
    /\b(?:booth|stand|space)\s*(?:#|no\.?|number)?\s*([A-Z]{0,2}\d{1,5}[A-Z]?)\b/i
  );
  if (labelled) return labelled[1];

  const withoutName = context.replace(name, " ").replace(/\s+/g, " ").trim();
  const bare = withoutName.match(/(?:^|\s)([A-Z]{0,2}\d{2,5}[A-Z]?)(?=\s|$)/);
  if (bare && !/^(19|20)\d{2}$/.test(bare[1])) return bare[1]; // not a year
  return null;
}

function linkClusterStrategy($: cheerio.CheerioAPI, sourceUrl: string): Company[] {
  const scrapedAt = new Date().toISOString();

  // Fingerprint each link by the PATH it points at, ignoring the query string.
  // Every exhibitor on a directory goes through the same handler
  // (…/Public/openURL.aspx?BoothID=…), while nav links point elsewhere.
  //
  // This replaced a CSS-class fingerprint, which silently split one directory
  // across several clusters: sites style their upgraded or sponsored listings
  // differently, so taking only the largest cluster dropped every exhibitor
  // that had paid for a better slot — the ones you most want to see.
  const clusters = new Map<string, Element[]>();

  $("a").each((_, el) => {
    const $el = $(el);
    const text = $el.text().replace(/\s+/g, " ").trim();
    if (!looksLikeCompany(text)) return;

    const href = $el.attr("href") ?? "";
    if (/^(mailto:|tel:|javascript:|#)/i.test(href)) return;

    const sig = `${linkFolder(href, sourceUrl)}@${depth($el)}`;

    if (!clusters.has(sig)) clusters.set(sig, []);
    clusters.get(sig)!.push(el);
  });

  let best: Element[] = [];
  for (const group of clusters.values()) {
    if (group.length > best.length) best = group;
  }
  if (best.length < 4) return [];

  const seen = new Set<string>();
  const out: Company[] = [];

  for (const el of best) {
    const $el = $(el);
    const name = $el.text().replace(/\s+/g, " ").trim();
    const key = name.toLowerCase();
    if (seen.has(key)) continue;
    seen.add(key);

    // Booth numbers sit in a sibling node, not the link itself.
    const context = spacedText($, $el.closest("li, tr, article, div").first());

    out.push({
      name,
      website: absolutise($el.attr("href"), sourceUrl),
      booth: findBooth(context, name),
      category: null,
      role: "unknown",
      sourceUrl,
      scrapedAt,
      evidence: (context || name).slice(0, 300),
    });
  }

  return out;
}
